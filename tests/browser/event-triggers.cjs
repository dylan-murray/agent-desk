// Real isolated HTTP server + real finite command workers. No model service is used.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const base=process.env.AGENT_DESK_TEST_URL;
if(!base||new URL(base).port==='4310'||!['localhost','127.0.0.1'].includes(new URL(base).hostname))throw Error('Set AGENT_DESK_TEST_URL to an isolated loopback server, never port 4310.');
const evidence=process.env.AGENT_DESK_EVENT_EVIDENCE_DIR||os.tmpdir();
const capture=(page,name)=>page.screenshot({path:path.join(evidence,'2026-09-16-event-triggers-'+name+'.png')});
const pause=ms=>new Promise(resolve=>setTimeout(resolve,ms));
(async()=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'desk-events-'));
  const browser=await chromium.launch({executablePath:process.env.CHROME_PATH,headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  page.on('dialog',()=>{throw Error('Native browser confirmation is not allowed');});
  let source,rule,token;
  const api=(route,payload)=>page.evaluate(({route,payload})=>terminalRequest(route,payload),{route,payload});
  const poll=async check=>{const deadline=Date.now()+30000;while(Date.now()<deadline){const result=await check();if(result)return result;await pause(150);}throw Error('Timed out waiting for event execution');};
  try{
    // Keep unrelated host session names out of screenshots. Event/workflow APIs are real.
    await page.route('**/api/agents',route=>route.fulfill({json:{agents:[]}}));
    await page.goto(base);await page.locator('#open-workflows').click();
    const openSources=()=>page.locator('#open-event-sources').click();
    const closeSources=()=>page.locator('.event-manager-close').click();
    await openSources();
    await page.locator('#new-event-source').click();
    await page.locator('#event-source-name').fill('Event check '+path.basename(root));
    await page.locator('#event-source-form [type=submit]').click();
    await page.locator('#event-token-dialog').waitFor();
    token=await page.locator('#event-webhook-token').inputValue();assert.ok(token.length>=40);
    const webhookUrl=await page.locator('#event-webhook-url').inputValue();
    assert.equal(new URL(webhookUrl).origin,new URL(base).origin);
    source=webhookUrl.split('/').pop();
    assert.equal(await page.locator('#event-socket-label').isVisible(),false);
    assert.ok(!(await page.locator('#event-webhook-example').textContent()).includes('--unix-socket'));
    await capture(page,'connection-desktop');
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.locator('#event-token-dialog').evaluate(d=>d.scrollWidth<=d.clientWidth&&d.getBoundingClientRect().right<=innerWidth));
    await capture(page,'connection-narrow');
    await page.setViewportSize({width:1440,height:1000});
    await page.locator('#event-token-dialog [data-close]').click();
    await page.waitForFunction(()=>document.getElementById('event-webhook-token').value==='');
    const sourceRow=()=>page.locator(`[data-source-id="${source}"]`);
    assert.match(await sourceRow().textContent(),/Paused/);
    await sourceRow().getByRole('button',{name:'Enable',exact:true}).click();
    await sourceRow().getByRole('button',{name:'Pause',exact:true}).waitFor();
    const command=`const fs=require('fs');const event=JSON.parse(process.env.AGENT_DESK_EVENT);fs.appendFileSync('observed.jsonl',JSON.stringify({id:event.id,phase:'start',at:Date.now(),payload:event.payload})+'\\n');console.log('EVENT '+event.id+' '+JSON.stringify(event.payload));setTimeout(()=>{fs.appendFileSync('observed.jsonl',JSON.stringify({id:event.id,phase:'end',at:Date.now()})+'\\n')},3500);`;
    const config=await api('/api/workflows/save-config',{name:'Event fixture command',kind:'command',cwd:root,argv:[process.execPath,'-e',command],timeout:15});
    await page.evaluate(()=>window.refreshWorkflows());
    await closeSources();
    await page.locator('#new-workflow').click();
    const name='Webhook proof '+path.basename(root);
    await page.locator('#schedule-name').fill(name);
    await page.locator('#schedule-trigger').selectOption('event');
    await page.locator('#schedule-event-source option').filter({hasText:path.basename(root)}).waitFor({state:'attached'});
    await page.locator('#schedule-event-source').selectOption(source);
    await page.locator('#schedule-event-field').fill('type');
    await page.locator('#schedule-event-value').fill('message');
    await page.locator('.schedule-task select').selectOption(config.id);
    assert.equal(await page.locator('#schedule-enabled').isEnabled(),false);
    await capture(page,'rule-desktop');
    // Annotation launcher remains reachable inside the new rule fields at narrow widths.
    await page.setViewportSize({width:390,height:844});
    await page.locator('#annotation-launcher').click();
    await page.waitForFunction(()=>document.getElementById('annotation-layer').parentElement.id==='schedule-dialog');
    assert.equal(await page.locator('#annotation-toolbar').isVisible(),true);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#schedule-dialog').evaluate(d=>d.open),true);
    assert.ok(await page.locator('#schedule-dialog').evaluate(d=>d.getBoundingClientRect().right<=innerWidth));
    await capture(page,'rule-narrow');
    await page.locator('#schedule-form [type=submit]').click();
    await page.locator('#schedule-dialog').waitFor({state:'hidden'});
    rule=(await api('/api/workflows')).workflows.find(w=>w.name===name);
    assert.equal(rule.enabled,false);
    const ruleRow=()=>page.locator('#schedule-rows tr').filter({hasText:name});
    const webhook=async(id,payload={type:'message'},customToken=token)=>{
      const response=await fetch(new URL('/api/event-bus/webhook/'+source,base),{method:'POST',headers:{'Content-Type':'application/json','Authorization':'Bearer '+customToken},body:JSON.stringify({id,payload})});
      return {status:response.status,body:await response.json()};
    };
    const ignored=await webhook('before-enabled');assert.equal(ignored.body.state,'ignored');
    assert.equal((await webhook('invalid-auth',{},'wrong')).status,403);
    assert.equal((await webhook('malformed',[])).status,400);
    // Replacing a token must leave old adapters unauthorized and keep the new token out of status.
    const priorToken=token;
    await openSources();
    await sourceRow().getByRole('button',{name:'New token',exact:true}).click();
    await page.locator('#event-confirm-action').click();await page.locator('#event-token-dialog').waitFor();
    token=await page.locator('#event-webhook-token').inputValue();assert.ok(token!==priorToken);
    await page.locator('#event-token-dialog [data-close]').click();
    assert.equal((await webhook('old-token',{},priorToken)).status,403);
    assert.ok(!JSON.stringify(await api('/api/event-bus')).includes(token));
    // In-use source deletion keeps its dialog and the refusal visible.
    await sourceRow().getByRole('button',{name:'Delete',exact:true}).click();
    await page.locator('#event-confirm-action').click();
    await page.waitForFunction(()=>document.querySelector('#event-source-confirm [role=alert]').textContent.includes('rules'));
    await page.locator('#event-source-confirm [data-close]').click();
    await page.setViewportSize({width:1440,height:1000});
    await closeSources();
    await ruleRow().getByRole('button',{name:'Enable',exact:true}).click();
    await ruleRow().getByRole('button',{name:'Pause',exact:true}).waitFor();
    assert.equal((await webhook('before-enabled')).body.duplicate,true);
    const first=await webhook('one',{type:'message',text:'payload reached worker'});assert.equal(first.status,202);
    await poll(async()=>{const state=await api('/api/workflows');return state.executions.some(e=>e.config_id===config.id&&e.state==='running');});
    const duplicate=await webhook('one');assert.equal(duplicate.status,200);assert.equal(duplicate.body.duplicate,true);
    assert.equal((await webhook('two')).status,202);
    const pending=await api('/api/event-bus');assert.equal(pending.events.find(e=>e.source_id===source&&e.event_id==='two').state,'pending');
    assert.equal((await api('/api/workflows')).flows.filter(f=>f.workflow_id===rule.id).length,1);
    const final=await poll(async()=>{const state=await api('/api/workflows');const runs=state.executions.filter(e=>e.config_id===config.id);return runs.length===2&&runs.every(e=>e.state==='succeeded')&&state;});
    const observations=fs.readFileSync(path.join(root,'observed.jsonl'),'utf8').trim().split('\n').map(JSON.parse);
    assert.deepEqual(observations.map(e=>e.id+':'+e.phase),['one:start','one:end','two:start','two:end']);
    assert.equal(observations[0].payload.text,'payload reached worker');
    assert.ok(observations[1].at<=observations[2].at);
    assert.equal(final.flows.filter(f=>f.workflow_id===rule.id).length,2);
    assert.equal((await webhook('one')).body.duplicate,true);
    for(const run of final.executions.filter(e=>e.config_id===config.id))assert.match((await api('/api/workflows/logs?id='+run.id)).text,/EVENT (one|two)/);
    await openSources();
    await page.locator('.event-deliveries summary').click();
    const delivered=page.locator('.event-delivery').filter({hasText:path.basename(root)}).filter({has:page.locator('code').getByText('one',{exact:true})});
    await poll(async()=>!!(await delivered.getByRole('button',{name:'View run'}).count()));
    await delivered.getByRole('button',{name:'View run'}).click();
    await page.locator('.run-detail').filter({hasText:'Event ·'}).waitFor();
    await openSources();
    await page.locator('.event-deliveries summary').click();
    // Last error is visible, not just persisted. Pausing stops admission.
    await webhook('bad-shape',[]);
    await poll(async()=>{await page.waitForTimeout(50);return (await sourceRow().textContent()).includes('JSON object');});
    await sourceRow().scrollIntoViewIfNeeded();await capture(page,'desktop');
    await page.setViewportSize({width:390,height:844});
    await sourceRow().scrollIntoViewIfNeeded();assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await capture(page,'narrow');
    await sourceRow().getByRole('button',{name:'Edit',exact:true}).click();
    await page.locator('#annotation-launcher').click();
    await page.waitForFunction(()=>document.getElementById('annotation-layer').parentElement.id==='event-source-dialog');
    assert.equal(await page.locator('#annotation-toolbar').isVisible(),true);
    await page.keyboard.press('Escape');
    await capture(page,'source-narrow');
    await page.locator('#event-source-dialog [data-close]').click();
    await sourceRow().getByRole('button',{name:'Pause',exact:true}).click();
    assert.equal((await webhook('source-paused')).status,409);
    await sourceRow().getByRole('button',{name:'Enable',exact:true}).click();
    await closeSources();
    await ruleRow().getByRole('button',{name:'Edit',exact:true}).click();
    assert.equal(await page.locator('#schedule-trigger').inputValue(),'event');
    await page.locator('#schedule-form [type=submit]').click();
    await page.locator('#schedule-dialog').waitFor({state:'hidden'});
    assert.equal((await api('/api/workflows')).workflows.find(w=>w.id===rule.id).enabled,false);
    await api('/api/workflows/delete',{id:rule.id});rule=null;
    await openSources();
    await sourceRow().getByRole('button',{name:'Delete',exact:true}).click();
    await page.locator('#event-source-confirm [data-close]').click();assert.equal(await sourceRow().count(),1);
    await sourceRow().getByRole('button',{name:'Delete',exact:true}).click();
    await page.locator('#event-confirm-action').click();await sourceRow().waitFor({state:'hidden'});source=null;
    assert.deepEqual(errors,[]);
    console.log('PASS: real source/rule CRUD, human enable, payload delivery, duplicate→200, busy event→queued, two sequential successful workers, visible health/errors, pause, edit revokes approval, desktop/narrow UI and modal annotations.');
    console.log('Observed command order: one:start → one:end → two:start → two:end; replay of one created no third run.');
  }finally{
    if(rule)await api('/api/workflows/delete',{id:rule.id}).catch(()=>{});
    if(source)await api('/api/event-bus/delete-source',{id:source}).catch(()=>{});
    await browser.close();fs.rmSync(root,{recursive:true,force:true});
  }
})().catch(e=>{console.error(e);process.exit(1)});
