const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const base=process.env.AGENT_DESK_TEST_URL;
if(!base||new URL(base).port==='4310'||!['localhost','127.0.0.1'].includes(new URL(base).hostname))throw Error('Set AGENT_DESK_TEST_URL to an isolated loopback server, never port 4310.');
const evidence=process.env.AGENT_DESK_CONFIG_EVIDENCE_DIR||os.tmpdir();
const capture=(page,name)=>page.screenshot({path:path.join(evidence,'2026-09-17-event-config-'+name+'.png'),animations:'disabled'});
(async()=>{
  const browser=await chromium.launch({executablePath:process.env.CHROME_PATH,headless:true});
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'desk-config-delete-'));
  const errors=[];let config,workflow,role,autoConfig;
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const api=(route,payload)=>page.evaluate(({route,payload})=>terminalRequest(route,payload),{route,payload});
  const poll=async check=>{const deadline=Date.now()+30000;while(Date.now()<deadline){const result=await check();if(result)return result;await page.waitForTimeout(100);}throw Error('Timed out waiting for fixture');};
  try{
    page.on('pageerror',e=>errors.push(e.message));page.on('dialog',()=>{throw Error('Native confirmation is not allowed');});
    await page.route('**/api/agents',route=>route.fulfill({json:{agents:[]}}));
    await page.goto(base);await page.locator('#open-workflows').click();
    await page.locator('#open-event-sources').click();
    await page.locator('#event-sources').getByRole('heading',{name:'Event sources',exact:true}).waitFor();
    await poll(async()=>await page.locator('#new-event-source').isEnabled());
    await page.locator('.event-manager-close').click();
    config=await api('/api/workflows/save-config',{name:'Review changed files '+path.basename(root),kind:'command',cwd:root,argv:[process.execPath,'-e','console.log("Retained configuration output")'],timeout:10});
    workflow=await api('/api/workflows/save',{name:'Config deletion history '+path.basename(root),trigger:'manual',nodes:[{id:'task-1',config_id:config.id,depends_on:[]}]});
    await api('/api/workflows/run',{id:workflow.id});
    const run=await poll(async()=>{const data=await api('/api/workflows');return data.executions.find(e=>e.config_id===config.id&&e.state==='succeeded');});
    await page.evaluate(()=>window.refreshWorkflows());
    const card=()=>page.locator('#run-configs article').filter({hasText:config.name});
    const dialog=page.locator('#run-config-delete-dialog');
    let deletes=0;page.on('request',r=>{if(new URL(r.url()).pathname==='/api/workflows/delete-config')deletes++;});
    await card().getByRole('button',{name:'Delete',exact:true}).click();
    assert.match(await dialog.textContent(),/Past runs, logs, and Inbox results stay available/);
    await dialog.getByRole('button',{name:'Keep configuration'}).click();assert.equal(deletes,0);
    await capture(page,'after');
    await card().getByRole('button',{name:'Delete',exact:true}).click();
    await dialog.getByRole('button',{name:'Delete configuration',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#run-config-delete-dialog [role=alert]').textContent.includes('Used by'));
    assert.equal(await card().count(),1);
    await capture(page,'delete-desktop');
    await page.setViewportSize({width:390,height:844});
    await page.locator('#annotation-launcher').click();
    await page.waitForFunction(()=>document.getElementById('annotation-layer').parentElement.id==='run-config-delete-dialog');
    assert.equal(await page.locator('#annotation-toolbar').isVisible(),true);
    await page.keyboard.press('Escape');
    assert.equal(await dialog.evaluate(d=>d.open),true);
    assert.ok(await dialog.evaluate(d=>d.getBoundingClientRect().right<=innerWidth));
    await capture(page,'delete-narrow');
    await api('/api/workflows/delete',{id:workflow.id});workflow=null;
    const before=deletes;
    await dialog.locator('.config-delete-confirm').evaluate(b=>{b.click();b.click();});
    await dialog.waitFor({state:'hidden'});await card().waitFor({state:'hidden'});
    assert.equal(deletes,before+1,'double clicks must send only one deletion');
    const saved=await api('/api/workflows');
    assert.ok(!saved.configs.some(c=>c.id===config.id));
    assert.equal(saved.executions.find(e=>e.id===run.id).config_name,config.name);
    assert.equal((await api('/api/workflows/logs?id='+run.id)).text.trim(),'Retained configuration output');
    await page.setViewportSize({width:1440,height:1000});
    await page.locator('#workflow-history .run-open').filter({hasText:'Config deletion history '+path.basename(root)}).click();
    const detail=page.locator('#run-detail-'+run.flow_id);
    assert.match(await detail.textContent(),new RegExp(config.name));
    assert.match(await detail.locator('.run-detail-summary').textContent(),/TriggerManual/);
    await detail.getByRole('button',{name:'Output',exact:true}).click();
    await page.locator('#run-log-dialog').waitFor({state:'visible'});
    assert.match(await page.locator('#run-log-title').textContent(),new RegExp(config.name));
    assert.match(await page.locator('#run-log-content').textContent(),/Retained configuration output/);
    await page.locator('#run-log-dialog .close-dialog').click();
    await page.locator('#open-inbox').click();
    await page.locator(`[data-inbox-item="${run.id}"]`).waitFor();
    assert.match(await page.locator(`[data-inbox-item="${run.id}"]`).textContent(),new RegExp(config.name));
    config=null;
    // Deleting an automation launch configuration keeps the saved automation itself.
    role=await api('/api/special-agents/save',{name:'Keep saved automation',kind:'watcher',scope:'Local fixtures',instructions:'No work',cwd:root,choice:'custom',command:process.execPath,mode:'direct'});
    autoConfig=await api('/api/workflows/save-config',{name:'Automation launch fixture',kind:'automation',role_id:role.id,timeout:10});
    await api('/api/workflows/delete-config',{id:autoConfig.id});autoConfig=null;
    assert.ok((await api('/api/special-agents')).roles.some(r=>r.id===role.id));
    const unauth=await fetch(new URL('/api/workflows/delete-config',base),{method:'POST',headers:{'Content-Type':'application/json'},body:'{"id":"unknown"}'});
    assert.equal(unauth.status,403);
    // An older live backend must explain activation rather than hiding Event sources.
    const legacy=await browser.newPage({viewport:{width:1440,height:1000}});legacy.on('pageerror',e=>errors.push(e.message));
    await legacy.route('**/api/**',route=>{
      const p=new URL(route.request().url()).pathname;
      if(p==='/api/event-bus'||p==='/api/workflows/delete-config')return route.fulfill({status:404,json:{error:'Not found'}});
      const fixtures={'/api/terminal-auth':{token:'fixture',cwd:'/tmp'},'/api/agents':{agents:[]},'/api/feedback':{notes:[],deleted:[]},'/api/workflows':{configs:[{id:'legacy',name:'Review changed files',kind:'command',cwd:'/tmp/event-demo'}],workflows:[],flows:[],executions:[]},'/api/special-agents':{roles:[],runs:[],inbox:[]},'/api/coordinators':{coordinators:[]}};
      return route.fulfill({json:fixtures[p]||{}});
    });
    await legacy.goto(base);await legacy.locator('#open-workflows').click();await legacy.locator('#open-event-sources').click();
    await legacy.waitForFunction(()=>document.getElementById('event-bus-status').textContent.includes('Restart Agent Desk'));
    assert.equal(await legacy.locator('#event-sources h2').isVisible(),true);
    assert.equal(await legacy.locator('#new-event-source').isEnabled(),false);
    assert.equal(await legacy.locator('#schedule-trigger option[value=event]').evaluate(option=>option.disabled),true);
    await capture(legacy,'update-pending');
    await legacy.locator('.event-manager-close').click();
    await legacy.locator('#run-configs').getByRole('button',{name:'Delete',exact:true}).click();
    await legacy.locator('.config-delete-confirm').click();
    await legacy.waitForFunction(()=>document.querySelector('#run-config-delete-dialog [role=alert]').textContent.includes('not been deleted'));
    assert.equal(await legacy.locator('#run-configs article').count(),1);
    assert.deepEqual(errors,[]);
    console.log('PASS: Event sources visible, real config deletion, confirmation/cancel/refusal, duplicate click guard, retained named history/logs/Inbox, saved automation retained, auth, narrow/modal annotations, explicit old-server activation state.');
  }finally{
    if(workflow)await api('/api/workflows/delete',{id:workflow.id}).catch(()=>{});
    for(const item of [config,autoConfig])if(item)await api('/api/workflows/delete-config',{id:item.id}).catch(()=>{});
    if(role)await api('/api/special-agents/delete',{id:role.id}).catch(()=>{});
    await browser.close();fs.rmSync(root,{recursive:true,force:true});
  }
})().catch(e=>{console.error(e);process.exit(1)});
